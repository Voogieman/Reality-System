const FALLBACK_VOICE: GodVoice = {
  genitive: 'бога',
  when: 'Когда нужен чужой голос, чтобы увидеть иначе',
  promise: 'Застрял — выбери голос и получи совет в образе, а не простыню текста.',
  prompt: 'Что я сейчас не вижу в своей ситуации?',
};

export function getGodVoice(god: SlavicGod): GodVoice {
  return GOD_VOICES[god.id] ?? FALLBACK_VOICE;
}

export function godVoiceTitle(god: SlavicGod): string {
  return `Голос ${getGodVoice(god).genitive}`;
}
